function requireScript(name, expected) {
  if (packageJson.scripts?.[name] !== expected) {
    failures.push(`package.json ${name} must be: ${expected}`);
  }
}

function requireScriptIncludes(name, expected) {
  const value = packageJson.scripts?.[name];
  if (typeof value !== "string" || !value.includes(expected)) {
    failures.push(`package.json ${name} script must include: ${expected}`);
  }
}

function requireTokens(path, tokens) {
  const source = files[path];
  for (const token of tokens) {
    if (!source.includes(token)) {
      failures.push(`${path} missing expected token: ${token}`);
    }
  }
}

function requireNoTokens(path, tokens) {
  const source = files[path];
  for (const token of tokens) {
    if (source.includes(token)) {
      failures.push(`${path} must not include token: ${token}`);
    }
  }
}

function requireOccurrenceCount(path, token, expectedCount) {
  const source = files[path];
  const count = source.split(token).length - 1;
  if (count !== expectedCount) {
    failures.push(`${path} must include token ${token} exactly ${expectedCount} time(s); found ${count}.`);
  }
}

function requireRegexCount(path, regex, expectedCount, label) {
  const source = files[path];
  const count = source.match(regex)?.length ?? 0;
  if (count !== expectedCount) {
    failures.push(`${path} must include ${label} exactly ${expectedCount} time(s); found ${count}.`);
  }
}

function requireNoTokensInFiles(label, paths, tokens) {
  for (const path of paths) {
    const source = readFileSync(path, "utf8");
    for (const token of tokens) {
      if (source.includes(token)) {
        failures.push(`${label} source ${path} must not include token: ${token}`);
      }
    }
  }
}

function collectSourceFiles(directory, extensions) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) return collectSourceFiles(path, extensions);
    if (entry.isFile() && extensions.some((extension) => path.endsWith(extension))) return [path];
    return [];
  });
}
